                "class DiversityMetric:\n",
                "    def compute(self, text: str) -> Dict:\n",
                "        tokens = re.findall(r'\\b[a-z]+\\b|[.,!?]', text.lower())\n",
                "        if not tokens: return {'distinct_1': 0.0, 'distinct_2': 0.0, 'diversity_score': 0.0}\n",
                "        \n",
                "        # Distinct-1\n",
                "        d1 = len(set(tokens)) / len(tokens)\n",
                "        \n",
                "        # Distinct-2\n",
                "        bigrams = [tuple(tokens[i:i+2]) for i in range(len(tokens)-1)]\n",
                "        d2 = len(set(bigrams)) / len(bigrams) if bigrams else 0.0\n",
                "        \n",
                "        return {'distinct_1': d1, 'distinct_2': d2, 'diversity_score': 0.4*d1 + 0.6*d2}\n",
                "    \n",
                "    def compute_corpus(self, texts: List[str]) -> Dict:\n",
                "        all_tokens = []\n",
