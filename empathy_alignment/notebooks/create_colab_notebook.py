                "class ReflectionLevelMetric:\n",
                "    def __init__(self):\n",
                "        self.complex_patterns = [\n",
                "            r'it seems like .+ means .+ to you', r'beneath .+ there seems to be',\n",
                "            r'on a deeper level', r'what that .+ represents',\n",
                "        ]\n",
                "        self.feeling_patterns = [\n",
                "            r\"you('re| are) feeling\", r'you feel', r'you seem',\n",
                "            r\"sounds like you('re| are)\", r'it sounds like',\n",
                "            r'that must (be|feel|have been)',\n",
                "            r\"i can (see|hear|sense|imagine) (that |how )?you\",\n",
                "        ]\n",
                "        self.simple_patterns = [\n",
                "            r'so you', r\"you('re| are) saying\", r'you mentioned',\n",
                "            r'i hear you', r'i understand', r'i see',\n",
                "            r\"that('s| is) (hard|difficult|tough|challenging)\",\n",
                "        ]\n",
                "        self.empathy_boosters = [\n",
                "            r\"i('m| am) sorry (to hear|that)\",\n",
                "            r'that must (be|have been) (really |very )?(hard|difficult|painful)',\n",
                "            r'i can only imagine', r'thank you for (sharing|telling)',\n",
                "        ]\n",
                "    \n",
                "    def compute(self, response: str, context: Optional[str] = None) -> Dict:\n",
                "        text = response.lower().strip()\n",
                "        counts = {'complex': 0, 'feeling': 0, 'simple': 0, 'booster': 0}\n",
                "        \n",
                "        for p in self.complex_patterns:\n",
                "            if re.search(p, text): counts['complex'] += 1\n",
                "        for p in self.feeling_patterns:\n",
                "            if re.search(p, text): counts['feeling'] += 1\n",
                "        for p in self.simple_patterns:\n",
                "            if re.search(p, text): counts['simple'] += 1\n",
                "        for p in self.empathy_boosters:\n",
                "            if re.search(p, text): counts['booster'] += 1\n",
                "        \n",
                "        if counts['complex'] > 0: level = 5 + min(counts['complex'], 1)\n",
                "        elif counts['feeling'] > 0: level = 3 + min(counts['feeling'], 2)\n",
                "        elif counts['simple'] > 0: level = 2 + min(counts['simple'] - 1, 1)\n",
                "        else: level = 0\n",
                "        \n",
                "        if counts['booster'] > 0 and level < 6: level = min(level + 1, 6)\n",
                "        \n",
                "        return {'level': level, 'normalized_score': level / 6.0}\n",
                "\n",
